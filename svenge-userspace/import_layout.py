"""Generate the compiled keymap from the saved WT75-C VIA matrix export."""
import argparse
import json
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
KEYMAP = HERE / "keyboards/wilba_tech/wt75_c/keymaps/svenge"
LAYOUT = KEYMAP / "wilba_tech_wt75_c.layout.json"
OUTPUT = KEYMAP / "layout.inc"
ALIASES = {
    "RESET": "QK_BOOT",
    "EF_DEC": "LM_PREV",
    "EF_INC": "LM_NEXT",
    "BR_DEC": "LM_BRID",
    "BR_INC": "LM_BRIU",
    "ES_DEC": "LM_SPDD",
    "ES_INC": "LM_SPDU",
}


def render_layout(data):
    if data.get("vendorProductId") != (0x6582 << 16 | 0x075C):
        raise ValueError("Expected a wilba.tech WT75-C VIA export (6582:075C)")
    if any(data.get("macros", [])) or data.get("encoders"):
        raise ValueError("Nonempty macros/encoders need a separate migration; refusing to omit them")
    layers = data.get("layers", [])
    if len(layers) != 4 or any(len(layer) != 6 * 16 for layer in layers):
        raise ValueError("Expected four layers with 96 matrix entries each")
    lines = [
        "// Copyright 2026 svenski88",
        "// SPDX-License-Identifier: GPL-2.0-or-later",
        "",
        "// Generated by python svenge-userspace/import_layout.py; edit the VIA export instead.",
        "// Electrical matrix rows preserve every slot, including absent switches.",
        "// clang-format off",
        "const uint16_t PROGMEM keymaps[][MATRIX_ROWS][MATRIX_COLS] = {",
    ]
    for number, layer in enumerate(layers):
        codes = []
        for code in layer:
            if not isinstance(code, str) or not re.fullmatch(r"[A-Z][A-Z0-9_]*(?:\([0-9]+\))?", code):
                raise ValueError(f"Unsupported keycode in layer {number}: {code!r}")
            codes.append(ALIASES.get(code, code))
        lines.append(f"    [{number}] = {{")
        for row in range(6):
            lines.append("        { " + ", ".join(f"{code:<8}" for code in codes[row * 16:(row + 1) * 16]) + " },")
        lines.append("    },")
    lines.extend(["};", "// clang-format on", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the compiled layout needs regeneration")
    args = parser.parse_args()
    rendered = render_layout(json.loads(LAYOUT.read_text(encoding="utf-8")))
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != rendered:
            parser.exit(1, "Compiled layout is stale; run python svenge-userspace/import_layout.py\n")
        print("PASS: all 384 compiled matrix entries match the saved VIA export and keycode translations")
    else:
        OUTPUT.write_text(rendered, encoding="utf-8", newline="\n")
        print(f"Generated {OUTPUT.relative_to(HERE)}")


if __name__ == "__main__":
    main()
